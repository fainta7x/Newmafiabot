import { test, expect } from '@playwright/test';
for (const width of [360,390]) test(`booking uses server facts and survives save failure at ${width}px`, async ({ page },info) => {
 await page.setViewportSize({width,height:740});
 await page.goto('/e2e/player-cabinet.html?booking=novice&route=%2Fplayer%2Fevents%2Fpreview-evening&saveFailures=1&slowSave=1');
 await expect(page.getByText('2/2',{exact:true})).toBeVisible();
 await expect(page.getByText(/нужно 2 игры/)).toBeVisible();
 await expect(page.getByText('9 игроков · собрано')).toHaveCount(2);
 const first=page.getByRole('button',{name:/Игра 1 ·/});
 await first.click();
 const save=page.getByRole('button',{name:'Сохранить мой план'});
 await save.click();
 await expect(page.getByRole('alert').filter({hasText:'Не удалось сохранить'})).toBeVisible();
 await save.click();
 await expect(first).toBeDisabled();
 await expect(page.getByRole('button',{name:'Весь вечер'})).toBeDisabled();
 await expect.poll(()=>page.evaluate(()=>typeof window.__releaseSlotSave)).toBe('function');
 await page.evaluate(()=>window.__releaseSlotSave());
 await expect(page.getByText('План сохранён')).toBeVisible();
 await expect(first).toBeEnabled();
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
 await page.screenshot({path:info.outputPath(`booking-novice-${width}.png`)});
 await page.goto('/e2e/player-cabinet.html?booking=rating&route=%2Fplayer%2Fevents%2Fpreview-evening');
 await expect(page.getByText(/500 ₽ за вечер/)).toBeVisible();
 await expect(page.getByText('500 ₽',{exact:true})).toBeVisible();
 await page.getByRole('button',{name:'Отменить запись'}).click();
 await expect(page.getByText('0 ₽',{exact:true})).toBeVisible();
 await page.getByRole('button',{name:'Весь вечер'}).click();
 await expect(page.getByText('500 ₽',{exact:true})).toBeVisible();
});
test('existing detail and payment failures recover without reloading the app',async({page})=>{
 await page.goto('/e2e/player-cabinet.html?booking=novice&route=%2Fplayer%2Fevents%2Fpreview-evening&slotFailures=1&overviewFailures=1');
 const slots=page.getByRole('alert').filter({hasText:'Не удалось загрузить игры'});
 const detail=page.getByRole('alert').filter({hasText:'Не удалось загрузить вечер'});
 await slots.getByRole('button',{name:'Повторить'}).click();
 await expect(page.getByRole('button',{name:/Игра 1 ·/})).toBeVisible();
 await detail.getByRole('button',{name:'Повторить'}).click();
 await expect(page.getByText('Вечер в деталях')).toBeVisible();
 await page.goto('/e2e/player-cabinet.html?route=%2Fplayer%2Fwallet%2Fpayments&paymentFailures=2');
 const error=page.getByTestId('player-payments-error');
 await expect(error).toBeVisible();
 await expect(page.getByText('Загрузка оплаты…',{exact:true})).toHaveCount(0);
 await error.getByRole('button',{name:'Повторить'}).click();
 await expect(error).toHaveCount(0);
 await expect(page.getByRole('heading',{name:'Долги и предстоящие вечера'})).toBeVisible();
});
