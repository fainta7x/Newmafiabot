export const normalizeGuideSearch = (value: string) => value.trim().toLocaleLowerCase('ru-RU').replace(/ё/g, 'е');

export const searchGlossary = (query: string, terms: GlossaryTerm[] = GLOSSARY) => {
  const q = normalizeGuideSearch(query);
  if (!q) return terms;
  return terms.filter((item) => [item.term, item.meaning, ...(item.aliases || [])].some((text) => normalizeGuideSearch(text).includes(q)));
};
