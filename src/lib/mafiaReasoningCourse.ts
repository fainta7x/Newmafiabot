export const reasoningLevelIndex = (id: string) => REASONING_LEVELS.findIndex((level) => level.id === id);
export const reasoningPassed = (score: number, level: ReasoningLevel) => score >= Math.ceil(reasoningMaxPoints(level) * 5 / 6);
