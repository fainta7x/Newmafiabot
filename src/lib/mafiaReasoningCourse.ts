/**
 * 2LA Noire — школа игрового мышления.
 * Не угадывание цвета и не тест правил. В каждом эпизоде два независимых шага:
 * выбор рабочей версии и проверка её причины/опровержения.
 *
 * Оценка: 2 — лучший из предложенных ходов анализа, 1 — допустимо с оговорками,
 * 0 — логическая ошибка. Ни один эпизод не утверждает, что красные не ошибаются,
 * а мафия всегда действует оптимально.
 */
export type ReasoningOption = { label: string; points: 0 | 1 | 2; feedback: string; plausible?: boolean };
export type ReasoningDecision = { prompt: string; options: ReasoningOption[]; mode?: 'multiple' };
export type ReasoningCase = { id: string; title: string; facts: string[]; steps: [ReasoningDecision, ReasoningDecision] };
export type ReasoningLevel = { id: string; title: string; skill: string; lead: string; cases: ReasoningCase[] };

const step = (prompt: string, options: Array<[string, 0 | 1 | 2, string]>): ReasoningDecision =>
  ({ prompt, options: options.map(([label, points, feedback]) => ({ label, points, feedback })) });

/** Multiple possible hypotheses can coexist. Mark statements as PLAUSIBLE, not proven.
 * Incorrect options contain an unjustified certainty or contradict a given fact.
 * The learner is graded on considering alternatives without accepting claims as facts.
 */
const multiple = (prompt: string, options: Array<[string, boolean, string]>): ReasoningDecision =>
  ({ prompt, mode: 'multiple', options: options.map(([label, plausible, feedback]) =>
    ({ label, plausible, points: plausible ? 2 : 0, feedback })) });

export type ReasoningAnswer = number | number[];
/** Two for all compatible explanations and no unsupported assertions;
 * one for an incomplete but non-contradictory set; zero if contradictions selected.
 */
export const reasoningDecisionPoints = (decision: ReasoningDecision, answer: ReasoningAnswer | undefined): 0 | 1 | 2 => {
  if (decision.mode !== 'multiple') return typeof answer === 'number' ? (decision.options[answer]?.points ?? 0) : 0;
  if (!Array.isArray(answer) || answer.length === 0) return 0;
  const chosen = new Set(answer);
  if (chosen.size !== answer.length || [...chosen].some((i) => !Number.isInteger(i) || i < 0 || i >= decision.options.length)) return 0;
  if ([...chosen].some((i) => !decision.options[i].plausible)) return 0;
  const possible = decision.options.filter((option) => option.plausible).length;
  return chosen.size === possible ? 2 : 1;
};

/** Permute every question's positions, independent of answer quality or label length.
 * Persist CANONICAL indices only: shuffling the display never corrupts old attempts.
 */
export const reasoningOptionOrder = (decision: ReasoningDecision, stepIndex: number, attempt: number): number[] => {
  const length = decision.options.length;
  const shift = ((stepIndex * 2 + attempt) % length + length) % length;
  return Array.from({ length }, (_, displayIndex) => (displayIndex + shift) % length);
};

