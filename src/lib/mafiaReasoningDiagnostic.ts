export const diagnosticForAttempt = (attempt: number): DiagnosticCase[] => {
  const offset = Number.isSafeInteger(attempt) && attempt >= 0 ? (attempt * 3) % DIAGNOSTIC_CASES.length : 0;
  return [0, 1, 2].map((index) => DIAGNOSTIC_CASES[(offset + index) % DIAGNOSTIC_CASES.length]);
};
