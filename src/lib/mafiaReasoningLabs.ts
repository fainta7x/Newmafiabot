/**
 * Advanced reasoning exercises. Pure, reviewed, scenario-based: never infer a role
 * from a facial expression, an unconfirmed sheriff claim or a single nomination.
 * Live Game state and scoring are NOT imported or mutated.
 */
export type LabTopicId = 'vote' | 'hypotheses' | 'timeline' | 'pressure' | 'action' | 'decide';
export type LabChoice = { label: string; points: 0 | 1 | 2; why: string };
export type LabStep = { phase: string; facts: string[]; question: string; options: [LabChoice, LabChoice, LabChoice] };
export type LabCase = { id: string; title: string; steps: LabStep[] };
export type LabTopic = { id: LabTopicId; title: string; detail: string; cases: LabCase[] };
type Choice = [string, 0 | 1 | 2, string];
const question = (phase: string, facts: string[], prompt: string, options: [Choice, Choice, Choice]): LabStep => ({
  phase, facts, question: prompt, options: options.map(([label, points, why]) => ({ label, points, why })) as LabStep['options'],
});

export type VotePlan = {
  id: string;
  alive: number[];
  black: number[];
  candidates: [number, number]; // first nominee is called before the second
  otherVotes: Record<number, number>; // planned votes of everyone except deciding player
  decidingPlayer: number;
};
export type VoteResult = {
  counts: Record<number, number>;
  votedOut: number | null;
  status: 'black_win_after_protocol' | 'red_win_after_protocol' | 'continues_after_protocol' | 'tie_needs_revote';
};

/** The voting is still FUTURE: raising at first candidate or leaving the ballot to the last one. */
export const calculateVoteResult = (plan: VotePlan, finalCandidate: number): VoteResult => {
  const { alive, black, candidates, decidingPlayer, otherVotes } = plan;
  const uniqueAlive = new Set(alive);
  const uniqueBlack = new Set(black);
  const voters = Object.keys(otherVotes).map(Number);
  if (alive.length < 5 || alive.length > 10 ||
    uniqueAlive.size !== alive.length ||
    [...uniqueAlive].some((id) => !Number.isInteger(id) || id < 1 || id > 10) ||
    uniqueBlack.size !== black.length || black.length < 1 || black.length * 2 >= alive.length ||
    black.some((id) => !uniqueAlive.has(id)) ||
    candidates[0] === candidates[1] || candidates.some((id) => !uniqueAlive.has(id)) ||
    !uniqueAlive.has(decidingPlayer) || voters.length !== alive.length - 1 ||
    new Set(voters).size !== voters.length || voters.includes(decidingPlayer) ||
    voters.some((id) => !uniqueAlive.has(id) || !candidates.includes(otherVotes[id]) || otherVotes[id] === id) ||
    !candidates.includes(finalCandidate) || decidingPlayer === finalCandidate
  ) throw new Error('Некорректное условие голосования');
  const counts = Object.fromEntries(candidates.map((id) => [id, 0])) as Record<number, number>;
  [...Object.values(otherVotes), finalCandidate].forEach((id) => { counts[id]++; });
  if (counts[candidates[0]] === counts[candidates[1]]) {
    return { counts, votedOut: null, status: 'tie_needs_revote' };
  }
  const votedOut = counts[candidates[0]] > counts[candidates[1]] ? candidates[0] : candidates[1];
  const blackAfter = black.length - Number(uniqueBlack.has(votedOut));
  const redAfter = alive.length - black.length - Number(!uniqueBlack.has(votedOut));
  return { counts, votedOut, status: blackAfter === 0 ? 'red_win_after_protocol' : blackAfter >= redAfter ? 'black_win_after_protocol' : 'continues_after_protocol' };
};

